using System;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace FutureDigitalPlus.UIKit.Location
{
    /// <summary>How the kit is installed in the project that is open in the editor.</summary>
    public enum KitInstall
    {
        /// <summary>The kit folder was not found in the AssetDatabase.</summary>
        NotFound = 0,

        /// <summary>A Unity package (<c>Packages/com.futuredigitalplus.uikit</c>): registry, git, local <c>file:</c> or embedded.</summary>
        Package = 1,

        /// <summary>A plain folder below <c>Assets</c> (the "classic" layout, generated by <c>Tools~/make_classic_kit.py</c>).</summary>
        Classic = 2,
    }

    /// <summary>
    /// Where the kit lives in the open project, whatever the layout. The same source works as a UPM package and as a plain folder
    /// below <c>Assets</c>, so no editor code or test may hard-code <c>Packages/com.futuredigitalplus.uikit</c> or
    /// <c>Assets/FutureDigitalPlus/UIKit</c>: ask this class. The kit folder is found by the GUID of its <c>Runtime</c> folder
    /// (the <c>.meta</c> files, and so the GUIDs, are identical in both layouts), so a renamed or moved install is found too.
    /// </summary>
    public static class KitLocation
    {
        /// <summary>GUID of the <c>Runtime</c> folder; the anchor that is searched for. Identical in both layouts.</summary>
        public const string RuntimeFolderGuid = "ab33b4cdd24f642ca998f78cea6394b9";

        /// <summary>The id of the kit as a UPM package.</summary>
        public const string PackageId = "com.futuredigitalplus.uikit";

        /// <summary>Default folder of the classic layout, relative to the project folder.</summary>
        public const string DefaultClassicAssetRoot = "Assets/FutureDigitalPlus/UIKit";

        /// <summary>
        /// Asset path of the kit folder (forward slashes, no trailing slash): <c>Packages/com.futuredigitalplus.uikit</c> or the
        /// folder below <c>Assets</c>. When the kit cannot be found it is the default of the layout that exists on disk
        /// (classic first), so callers get a usable string; check <see cref="Install"/> to tell.
        /// </summary>
        public static string AssetRoot
        {
            get
            {
                string found = FindAssetRoot();
                if (found != null) return found;
                return Directory.Exists(DefaultClassicAssetRoot) ? DefaultClassicAssetRoot : "Packages/" + PackageId;
            }
        }

        /// <summary>How the kit is installed, or <see cref="KitInstall.NotFound"/>.</summary>
        public static KitInstall Install
        {
            get
            {
                string found = FindAssetRoot();
                if (found == null) return KitInstall.NotFound;
                return found.StartsWith("Packages/", StringComparison.Ordinal) ? KitInstall.Package : KitInstall.Classic;
            }
        }

        /// <summary>True when the kit is a plain folder below <c>Assets</c>.</summary>
        public static bool IsClassic => Install == KitInstall.Classic;

        /// <summary>
        /// True when files of the kit can be written: always for the classic layout, and for an embedded or local-path package.
        /// False for a package installed from a registry, a git URL or the built-in folder.
        /// </summary>
        public static bool IsWritable
        {
            get
            {
                string root = AssetRoot;
                if (!root.StartsWith("Packages/", StringComparison.Ordinal)) return true;
                var info = UnityEditor.PackageManager.PackageInfo.FindForAssetPath(root);
                return info == null ||
                       info.source == UnityEditor.PackageManager.PackageSource.Embedded ||
                       info.source == UnityEditor.PackageManager.PackageSource.Local;
            }
        }

        /// <summary>Absolute path of the kit folder on disk (no trailing separator).</summary>
        public static string FullPath => ToFullPath(AssetRoot);

        /// <summary>Asset path of a file or folder inside the kit, for example <c>Runtime/DesignSystem</c>.</summary>
        /// <param name="relative">Path relative to the kit folder, forward slashes.</param>
        public static string AssetPath(string relative) =>
            string.IsNullOrEmpty(relative) ? AssetRoot : AssetRoot + "/" + relative.TrimStart('/');

        /// <summary>Absolute path on disk of a file or folder inside the kit.</summary>
        /// <param name="relative">Path relative to the kit folder, forward slashes.</param>
        public static string FullPathOf(string relative) =>
            string.IsNullOrEmpty(relative) ? FullPath : Path.Combine(FullPath, relative.TrimStart('/'));

        private static string FindAssetRoot()
        {
            string runtime = AssetDatabase.GUIDToAssetPath(RuntimeFolderGuid);
            if (string.IsNullOrEmpty(runtime)) return null;
            int cut = runtime.LastIndexOf('/');
            return cut > 0 ? runtime.Substring(0, cut) : null;
        }

        private static string ToFullPath(string assetPath)
        {
            string full;
            if (assetPath.StartsWith("Packages/", StringComparison.Ordinal))
            {
                var info = UnityEditor.PackageManager.PackageInfo.FindForAssetPath(assetPath);
                full = info != null ? info.resolvedPath : Path.GetFullPath(assetPath);
            }
            else
            {
                full = Path.Combine(Directory.GetParent(Application.dataPath).FullName, assetPath);
            }

            return Path.GetFullPath(full).TrimEnd('/', '\\');
        }
    }
}
